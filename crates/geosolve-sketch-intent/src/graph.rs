fn validate_operation_outputs(
    node: NodeId,
    kind: &IntentNodeKind,
    outputs: &[IntentOperationOutput],
) -> Result<(), IntentGraphError> {
    let IntentNodeKind::Operation { operation } = kind else {
        if outputs.is_empty() {
            return Ok(());
        }
        return Err(IntentGraphError::InvalidPortSchema { node });
    };
    if outputs.len() > MAX_INTENT_OPERATION_OUTPUTS {
        return Err(IntentGraphError::ResourceLimit {
            resource: "operation outputs",
            actual: outputs.len(),
            limit: MAX_INTENT_OPERATION_OUTPUTS,
        });
    }
    if matches!(
        operation,
        crate::OperationKind::Split
            | crate::OperationKind::Break
            | crate::OperationKind::Trim
            | crate::OperationKind::Extend
    ) && !outputs.is_empty()
    {
        return Err(IntentGraphError::InvalidPortSchema { node });
    }
    let mut spans = 0_usize;
    for output in outputs {
        match output.kind {
            IntentOperationOutputKind::Curve if output.curve_span_count == 0 => {
                return Err(IntentGraphError::InvalidPortSchema { node });
            }
            IntentOperationOutputKind::Curve => {
                spans = spans
                    .checked_add(usize::from(output.curve_span_count))
                    .ok_or(IntentGraphError::InvalidPortSchema { node })?;
            }
            _ if output.curve_span_count != 0 => {
                return Err(IntentGraphError::InvalidPortSchema { node });
            }
            _ => {}
        }
    }
    if spans > usize::from(u16::MAX) {
        return Err(IntentGraphError::ResourceLimit {
            resource: "operation curve spans",
            actual: spans,
            limit: usize::from(u16::MAX),
        });
    }
    Ok(())
}

fn validate_declaration_inputs<T>(
    node: NodeId,
    kind: &IntentNodeKind,
    schema: &crate::IntentNodeSchema,
    inputs: &BTreeMap<InputSlot, T>,
) -> Result<(), IntentGraphError> {
    for slot in inputs.keys() {
        let Some(cardinality) = schema.input(slot.role) else {
            return Err(IntentGraphError::UnexpectedInputSlot { node, slot: *slot });
        };
        if slot.index >= cardinality.maximum {
            return Err(IntentGraphError::UnexpectedInputSlot { node, slot: *slot });
        }
    }
    for cardinality in &schema.inputs {
        let actual = inputs
            .keys()
            .filter(|slot| slot.role == cardinality.role)
            .count();
        let actual = u16::try_from(actual).map_err(|_| IntentGraphError::ResourceLimit {
            resource: "node input role cardinality",
            actual,
            limit: usize::from(u16::MAX),
        })?;
        if actual < cardinality.minimum {
            return Err(IntentGraphError::MissingRequiredInput {
                node,
                slot: InputSlot::new(cardinality.role, actual),
            });
        }
        if actual > cardinality.maximum {
            return Err(IntentGraphError::UnexpectedInputSlot {
                node,
                slot: InputSlot::new(cardinality.role, cardinality.maximum),
            });
        }
        // Geometry recipes retain the semantic authored-point slot on each
        // output port. Any subset may alias pre-existing points while the
        // remaining slots allocate new native points, so those optional
        // aliases are intentionally sparse. Exact relation, dimension,
        // aggregate and operation operand lists remain contiguous.
        let sparse_geometry_points =
            matches!(kind, IntentNodeKind::Geometry { .. }) && cardinality.role == InputRole::Point;
        if !sparse_geometry_points {
            for index in 0..actual {
                let slot = InputSlot::new(cardinality.role, index);
                if !inputs.contains_key(&slot) {
                    return Err(IntentGraphError::MissingRequiredInput { node, slot });
                }
            }
        }
    }
    for choice in &schema.input_choices {
        let actual = choice
            .alternatives
            .iter()
            .filter(|slot| inputs.contains_key(slot))
            .count();
        if actual < usize::from(choice.minimum) || actual > usize::from(choice.maximum) {
            return Err(IntentGraphError::InputChoiceCardinality {
                node,
                minimum: choice.minimum,
                maximum: choice.maximum,
                actual,
            });
        }
    }
    Ok(())
}

fn allocate_port_spec(
    node: NodeId,
    spec: PortSpec,
    reserve: bool,
    allocator: &mut IntentAllocatorHighWater,
    ports: &mut BTreeMap<PortId, AllocatedPort>,
    reservations: &mut BTreeMap<ReservationId, IntentReservation>,
) -> Result<PortId, IntentGraphError> {
    let id = allocator.allocate_port()?;
    let reservation = if reserve {
        let value = allocator.allocate_reservation()?;
        let kind = spec
            .native
            .ok_or(IntentGraphError::InvalidPortSchema { node })?;
        reservations.insert(
            value,
            IntentReservation {
                id: value,
                kind,
                paired_with: None,
            },
        );
        Some(value)
    } else {
        None
    };
    ports.insert(
        id,
        AllocatedPort {
            id,
            spec,
            reservation,
        },
    );
    Ok(id)
}

fn pair_native_reservations(
    node: NodeId,
    ports: &BTreeMap<PortId, AllocatedPort>,
    reservations: &mut BTreeMap<ReservationId, IntentReservation>,
) -> Result<(), IntentGraphError> {
    for (owner, source) in [
        (
            IntentNativeReservationKind::Constraint,
            IntentNativeReservationKind::ConstraintSource,
        ),
        (
            IntentNativeReservationKind::Dimension,
            IntentNativeReservationKind::DimensionSource,
        ),
    ] {
        let reservations_for = |kind| {
            ports
                .values()
                .filter(|port| port.spec.native == Some(kind))
                .filter_map(|port| port.reservation)
                .collect::<Vec<_>>()
        };
        let owners = reservations_for(owner);
        let sources = reservations_for(source);
        if owners.len() != sources.len() {
            let reservation = owners
                .first()
                .or_else(|| sources.first())
                .copied()
                .ok_or(IntentGraphError::InvalidPortSchema { node })?;
            return Err(IntentGraphError::InvalidReservationPair { node, reservation });
        }
        for (owner_id, source_id) in owners.into_iter().zip(sources) {
            if source_id.raw() != owner_id.raw().checked_add(1).unwrap_or_default() {
                return Err(IntentGraphError::InvalidReservationPair {
                    node,
                    reservation: owner_id,
                });
            }
            reservations
                .get_mut(&owner_id)
                .expect("allocated owner reservation")
                .paired_with = Some(source_id);
            reservations
                .get_mut(&source_id)
                .expect("allocated source reservation")
                .paired_with = Some(owner_id);
        }
    }
    Ok(())
}

