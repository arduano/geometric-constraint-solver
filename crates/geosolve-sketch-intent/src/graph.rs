/// One closed typed declaration in the unordered graph.
#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct IntentNode {
    pub id: NodeId,
    pub symbol: crate::IntentKey,
    pub kind: IntentNodeKind,
    /// Exact historical native object retained when a supported bootstrap
    /// declaration is projectionally ejected into a typed declaration.
    ///
    /// This origin is host-decoded reconstruction evidence, not a second
    /// geometry definition. Callers cannot set it through [`IntentNodeDraft`].
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub bootstrap_origin: Option<IntentBootstrapObject>,
    pub suppressed: bool,
    pub inputs: BTreeMap<crate::InputSlot, IntentPortRef>,
    pub fields: BTreeMap<IntentFieldKey, IntentLiteral>,
    /// Untrusted operation output shape authenticated against the existing
    /// Rust operation proposal before any reservation is consumed.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub operation_outputs: Vec<IntentOperationOutput>,
    pub ports: BTreeMap<PortId, IntentPort>,
    pub reservations: BTreeMap<ReservationId, IntentReservation>,
    pub child_order: Vec<ChildId>,
    pub children: BTreeMap<ChildId, IntentChild>,
}

impl IntentNode {
    #[must_use]
    pub fn port(&self, id: PortId) -> Option<&IntentPort> {
        self.ports.get(&id)
    }

    #[must_use]
    pub fn port_by_selector(&self, selector: IntentPortSelector) -> Option<&IntentPort> {
        self.ports.values().find(|port| port.selector == selector)
    }

    #[must_use]
    pub fn dependencies(&self) -> BTreeSet<NodeId> {
        self.inputs
            .values()
            .map(|source| source.node)
            .chain(self.ports.values().filter_map(|port| match port.flow {
                IntentIdentityFlow::OwnedLogical | IntentIdentityFlow::Created { .. } => None,
                IntentIdentityFlow::Aliased { source }
                | IntentIdentityFlow::Continued { source, .. }
                | IntentIdentityFlow::Retired { source, .. } => Some(source.node),
            }))
            .collect()
    }
}

/// Unordered canonical stable declaration graph.
#[derive(Clone, Debug, Deserialize, PartialEq, Serialize)]
#[serde(deny_unknown_fields)]
pub struct IntentGraph {
    pub(crate) revision: Revision,
    pub(crate) nodes: BTreeMap<NodeId, IntentNode>,
}

impl IntentGraph {
    #[must_use]
    pub fn empty() -> Self {
        Self {
            revision: Revision::from_raw(0),
            nodes: BTreeMap::new(),
        }
    }

    #[must_use]
    pub fn nodes(&self) -> &BTreeMap<NodeId, IntentNode> {
        &self.nodes
    }

    #[must_use]
    pub fn node(&self, id: NodeId) -> Option<&IntentNode> {
        self.nodes.get(&id)
    }

    /// Resolves one durable developer-facing symbol independently of display
    /// name and organization order.
    #[must_use]
    pub fn node_by_symbol(&self, symbol: &crate::IntentKey) -> Option<&IntentNode> {
        self.nodes.values().find(|node| &node.symbol == symbol)
    }

    /// Reclassifies one exact native Point bootstrap as the supported typed
    /// Sketch Point declaration without allocating or renumbering anything.
    ///
    /// The node, port, reservation, writable leaves, symbol, organization and
    /// every downstream reference retain their stable identities. The exact
    /// bootstrap payload moves into `bootstrap_origin` so cold reconstruction
    /// and canonical reload can continue to authenticate the native point.
    pub(crate) fn eject_bootstrap_point(&mut self, node: NodeId) -> Result<(), IntentGraphError> {
        let target = self
            .nodes
            .get_mut(&node)
            .ok_or(IntentGraphError::UnknownNode(node))?;
        let IntentNodeKind::Bootstrap { object } = &target.kind else {
            return Err(IntentGraphError::UnsupportedBootstrapEjection { node });
        };
        if object.kind != BootstrapNativeKind::Point {
            return Err(IntentGraphError::UnsupportedBootstrapEjection { node });
        }
        if target.bootstrap_origin.is_some()
            || target.suppressed
            || !target.fields.is_empty()
            || !target.operation_outputs.is_empty()
            || !target.child_order.is_empty()
            || !target.children.is_empty()
            || target.inputs.len() != 1
            || !target
                .inputs
                .contains_key(&InputSlot::new(InputRole::Identity, 0))
        {
            return Err(IntentGraphError::IncompleteBootstrapEjection { node });
        }
        let primary = target
            .port_by_selector(IntentPortSelector::Node {
                role: crate::IntentPortRole::Primary,
                index: 0,
            })
            .ok_or(IntentGraphError::IncompleteBootstrapEjection { node })?;
        let IntentIdentityFlow::Created { reservation } = primary.flow else {
            return Err(IntentGraphError::IncompleteBootstrapEjection { node });
        };
        if primary.kind != IntentPortKind::Point
            || primary.writable != [LeafField::X, LeafField::Y]
            || target.reservations.len() != 1
            || target
                .reservations
                .get(&reservation)
                .map(|entry| entry.kind)
                != Some(IntentNativeReservationKind::Point)
        {
            return Err(IntentGraphError::IncompleteBootstrapEjection { node });
        }

        let origin = object.clone();
        target.kind = IntentNodeKind::Geometry {
            recipe: GeometryRecipeKind::SketchPoint,
        };
        target.bootstrap_origin = Some(origin);
        target.inputs.clear();
        Ok(())
    }

    #[must_use]
    pub fn port(&self, reference: IntentPortRef) -> Option<&IntentPort> {
        self.nodes
            .get(&reference.node)
            .and_then(|node| node.ports.get(&reference.port))
            .filter(|port| port.kind == reference.kind)
    }

    #[must_use]
    pub fn identity(&self) -> IntentGraphIdentity {
        IntentGraphIdentity(ComponentIdentity {
            revision: self.revision,
            digest: self.digest(),
        })
    }

    /// Computes the exact canonical graph content digest.
    ///
    /// # Panics
    ///
    /// Panics only if serialization of this closed in-memory schema fails,
    /// which its `Serialize` implementation cannot ordinarily do.
    #[must_use]
    pub fn digest(&self) -> ContentDigest {
        digest_bytes(
            &serde_json::to_vec(&(self.revision, &self.nodes))
                .expect("intent graph is infallibly serializable"),
        )
    }

    /// Returns the canonical stable dependency schedule. Presentation order is
    /// never consulted; stable IDs break every ready-set tie.
    ///
    /// # Errors
    ///
    /// Returns a structural error for an unknown dependency or dependency cycle.
    pub fn canonical_schedule(&self) -> Result<Vec<NodeId>, IntentGraphError> {
        canonical_schedule(&self.nodes)
    }

    /// Computes the exact transitive dependent closure, including each root.
    ///
    /// # Errors
    ///
    /// Returns [`IntentGraphError::UnknownNode`] when a root is absent.
    pub fn dependent_closure(
        &self,
        roots: impl IntoIterator<Item = NodeId>,
    ) -> Result<BTreeSet<NodeId>, IntentGraphError> {
        let roots = roots.into_iter().collect::<BTreeSet<_>>();
        for root in &roots {
            if !self.nodes.contains_key(root) {
                return Err(IntentGraphError::UnknownNode(*root));
            }
        }
        let mut reverse = BTreeMap::<NodeId, BTreeSet<NodeId>>::new();
        for (node, value) in &self.nodes {
            for dependency in value.dependencies() {
                reverse.entry(dependency).or_default().insert(*node);
            }
        }
        let mut closure = roots.clone();
        let mut pending = roots;
        while let Some(node) = pending.pop_first() {
            if let Some(dependents) = reverse.get(&node) {
                for dependent in dependents {
                    if closure.insert(*dependent) {
                        pending.insert(*dependent);
                    }
                }
            }
        }
        Ok(closure)
    }

    /// Validates all schema, reference, DAG, reservation, and identity-flow
    /// invariants without materializing geometry.
    ///
    /// # Errors
    ///
    /// Returns the first bounded structural, schema, lifecycle, or wire-value
    /// violation.
    #[allow(
        clippy::too_many_lines,
        reason = "one validation pass keeps cross-schema graph invariants auditable"
    )]
    pub fn validate(&self) -> Result<(), IntentGraphError> {
        if self.nodes.len() > MAX_INTENT_NODES {
            return Err(IntentGraphError::ResourceLimit {
                resource: "intent nodes",
                actual: self.nodes.len(),
                limit: MAX_INTENT_NODES,
            });
        }
        let mut ports = BTreeMap::<PortId, (NodeId, &IntentPort)>::new();
        let mut reservations = BTreeSet::new();
        let mut children = BTreeSet::new();
        let mut symbols = BTreeSet::new();
        for (id, node) in &self.nodes {
            if *id != node.id {
                return Err(IntentGraphError::MapKeyMismatch { kind: "node" });
            }
            if !symbols.insert(&node.symbol) {
                return Err(IntentGraphError::DuplicateSymbol(node.symbol.clone()));
            }
            if node.inputs.len() > MAX_INTENT_NODE_INPUTS {
                return Err(IntentGraphError::ResourceLimit {
                    resource: "node inputs",
                    actual: node.inputs.len(),
                    limit: MAX_INTENT_NODE_INPUTS,
                });
            }
            if node.fields.len() > MAX_INTENT_NODE_FIELDS {
                return Err(IntentGraphError::ResourceLimit {
                    resource: "node fields",
                    actual: node.fields.len(),
                    limit: MAX_INTENT_NODE_FIELDS,
                });
            }
            for value in node.fields.values() {
                value.validate()?;
            }
            validate_operation_outputs(*id, &node.kind, &node.operation_outputs)?;
            if let IntentNodeKind::Bootstrap { object } = &node.kind {
                object.validate()?;
            }
            if let Some(origin) = &node.bootstrap_origin {
                origin.validate()?;
                if origin.kind != BootstrapNativeKind::Point
                    || !matches!(
                        node.kind,
                        IntentNodeKind::Geometry {
                            recipe: GeometryRecipeKind::SketchPoint
                        }
                    )
                    || node.suppressed
                    || !node.inputs.is_empty()
                {
                    return Err(IntentGraphError::InvalidBootstrapEjection { node: *id });
                }
            }
            let dynamic_children = u16::try_from(node.children.len())
                .map_err(|_| IntentGraphError::InvalidChildSchema { node: *id })?;
            validate_declaration_schema(
                *id,
                &node.kind,
                dynamic_children,
                &node.inputs,
                &node.fields,
            )?;
            for (slot, source) in &node.inputs {
                if !node.kind.accepts_input(slot.role) {
                    return Err(IntentGraphError::InputRoleNotAccepted {
                        node: *id,
                        role: slot.role,
                    });
                }
                if let Some(expected) = slot.role.expected_kind()
                    && expected != source.kind
                {
                    return Err(IntentGraphError::InputKindMismatch {
                        node: *id,
                        expected,
                        actual: source.kind,
                    });
                }
            }
            if node.child_order.len() != node.children.len()
                || node.child_order.iter().collect::<BTreeSet<_>>().len() != node.child_order.len()
            {
                return Err(IntentGraphError::InvalidChildOrder { node: *id });
            }
            for child in &node.child_order {
                let value = node
                    .children
                    .get(child)
                    .ok_or(IntentGraphError::InvalidChildOrder { node: *id })?;
                if value.id != *child || !children.insert(*child) {
                    return Err(IntentGraphError::DuplicateIdentity { kind: "child" });
                }
                if value.schema != node.kind.child_schema() {
                    return Err(IntentGraphError::InvalidChildSchema { node: *id });
                }
                for port in &value.ports {
                    if !node.ports.contains_key(port) {
                        return Err(IntentGraphError::UnknownChildPort {
                            node: *id,
                            port: *port,
                        });
                    }
                }
            }
            validate_schema_ports(node)?;
            for (port_id, port) in &node.ports {
                if *port_id != port.id || ports.insert(*port_id, (*id, port)).is_some() {
                    return Err(IntentGraphError::DuplicateIdentity { kind: "port" });
                }
                let mut writable = port.writable.clone();
                writable.sort_unstable();
                writable.dedup();
                if writable != port.writable {
                    return Err(IntentGraphError::InvalidWritableLeaves { node: *id });
                }
            }
            for (reservation_id, reservation) in &node.reservations {
                if *reservation_id != reservation.id || !reservations.insert(*reservation_id) {
                    return Err(IntentGraphError::DuplicateIdentity {
                        kind: "reservation",
                    });
                }
                if let Some(pair) = reservation.paired_with {
                    let Some(companion) = node.reservations.get(&pair) else {
                        return Err(IntentGraphError::UnknownReservation {
                            node: *id,
                            reservation: pair,
                        });
                    };
                    let valid_pair = companion.paired_with == Some(*reservation_id)
                        && matches!(
                            (reservation.kind, companion.kind),
                            (
                                IntentNativeReservationKind::Constraint,
                                IntentNativeReservationKind::ConstraintSource
                            ) | (
                                IntentNativeReservationKind::ConstraintSource,
                                IntentNativeReservationKind::Constraint
                            ) | (
                                IntentNativeReservationKind::Dimension,
                                IntentNativeReservationKind::DimensionSource
                            ) | (
                                IntentNativeReservationKind::DimensionSource,
                                IntentNativeReservationKind::Dimension
                            )
                        );
                    if !valid_pair {
                        return Err(IntentGraphError::InvalidReservationPair {
                            node: *id,
                            reservation: *reservation_id,
                        });
                    }
                } else if matches!(
                    reservation.kind,
                    IntentNativeReservationKind::Constraint
                        | IntentNativeReservationKind::ConstraintSource
                        | IntentNativeReservationKind::Dimension
                        | IntentNativeReservationKind::DimensionSource
                ) {
                    return Err(IntentGraphError::InvalidReservationPair {
                        node: *id,
                        reservation: *reservation_id,
                    });
                }
            }
        }

        for (node_id, node) in &self.nodes {
            for source in node.inputs.values() {
                validate_port_reference(*node_id, *source, &ports)?;
            }
            for port in node.ports.values() {
                match port.flow {
                    IntentIdentityFlow::OwnedLogical => {}
                    IntentIdentityFlow::Created { reservation } => {
                        let value = node.reservations.get(&reservation).ok_or(
                            IntentGraphError::UnknownReservation {
                                node: *node_id,
                                reservation,
                            },
                        )?;
                        if value.kind.port_kind() != port.kind {
                            return Err(IntentGraphError::ReservationKindMismatch {
                                node: *node_id,
                                port: port.id,
                            });
                        }
                    }
                    IntentIdentityFlow::Aliased { source }
                    | IntentIdentityFlow::Continued { source, .. }
                    | IntentIdentityFlow::Retired { source, .. } => {
                        validate_port_reference(*node_id, source, &ports)?;
                        if source.kind != port.kind {
                            return Err(IntentGraphError::IdentityKindMismatch {
                                node: *node_id,
                                expected: port.kind,
                                actual: source.kind,
                            });
                        }
                    }
                }
            }
        }

        let schedule = canonical_schedule(&self.nodes)?;
        validate_identity_flow(&schedule, &self.nodes)?;
        Ok(())
    }

    pub(crate) fn set_suppressed(
        &mut self,
        node: NodeId,
        suppressed: bool,
    ) -> Result<bool, IntentGraphError> {
        let value = self
            .nodes
            .get_mut(&node)
            .ok_or(IntentGraphError::UnknownNode(node))?;
        let changed = value.suppressed != suppressed;
        value.suppressed = suppressed;
        Ok(changed)
    }

    pub(crate) fn set_field(
        &mut self,
        node: NodeId,
        field: IntentFieldKey,
        value: IntentLiteral,
    ) -> Result<bool, IntentGraphError> {
        value.validate()?;
        let node = self
            .nodes
            .get_mut(&node)
            .ok_or(IntentGraphError::UnknownNode(node))?;
        if node.fields.get(&field) == Some(&value) {
            return Ok(false);
        }
        node.fields.insert(field, value);
        Ok(true)
    }

    pub(crate) fn rebind_input(
        &mut self,
        node: NodeId,
        slot: crate::InputSlot,
        source: IntentPortRef,
    ) -> Result<bool, IntentGraphError> {
        let target = self
            .nodes
            .get_mut(&node)
            .ok_or(IntentGraphError::UnknownNode(node))?;
        if !target.kind.accepts_input(slot.role) {
            return Err(IntentGraphError::InputRoleNotAccepted {
                node,
                role: slot.role,
            });
        }
        if let Some(expected) = slot.role.expected_kind()
            && expected != source.kind
        {
            return Err(IntentGraphError::InputKindMismatch {
                node,
                expected,
                actual: source.kind,
            });
        }
        let Some(previous) = target.inputs.get(&slot).copied() else {
            return Err(IntentGraphError::UnknownInputSlot { node, slot });
        };
        if previous == source {
            return Ok(false);
        }

        let dynamic_children = u16::try_from(target.children.len())
            .map_err(|_| IntentGraphError::InvalidPortSchema { node })?;
        let mut specs = node_port_specs(
            &target.kind,
            &target.fields,
            dynamic_children,
            &target.operation_outputs,
        );
        for (ordinal, child) in target.child_order.iter().enumerate() {
            let ordinal =
                u16::try_from(ordinal).map_err(|_| IntentGraphError::InvalidPortSchema { node })?;
            specs.extend(child_port_specs(
                &target.kind,
                target.children[child].schema,
                ordinal,
                dynamic_children,
                &target.fields,
            ));
        }
        for spec in specs
            .into_iter()
            .filter(|spec| spec.alias_input == Some(slot))
        {
            let port = target
                .ports
                .values_mut()
                .find(|port| port.selector == spec.selector)
                .ok_or(IntentGraphError::InvalidPortSchema { node })?;
            port.flow = IntentIdentityFlow::Aliased { source };
        }
        if let IntentNodeKind::Identity { transition, .. } = &target.kind {
            for port in target.ports.values_mut() {
                port.flow = match *transition {
                    crate::IdentityTransitionKind::Alias => IntentIdentityFlow::Aliased { source },
                    crate::IdentityTransitionKind::Continue => IntentIdentityFlow::Continued {
                        source,
                        generation: 0,
                    },
                    crate::IdentityTransitionKind::Retire => IntentIdentityFlow::Retired {
                        source,
                        generation: 0,
                    },
                };
            }
        }
        target.inputs.insert(slot, source);
        Ok(true)
    }

    pub(crate) fn remove_nodes(
        &mut self,
        nodes: &BTreeSet<NodeId>,
        instance: &mut IntentInstanceState,
    ) {
        for node in nodes {
            self.nodes.remove(node);
        }
        instance
            .values
            .retain(|leaf, _| !nodes.contains(&leaf.node));
    }

    /// Resolves one declared writable leaf to its owning stable output.
    ///
    /// # Errors
    ///
    /// Returns a typed graph error when the node or port is absent, or when
    /// the requested field is not writable on that output.
    pub fn writable_leaf(&self, leaf: LeafRef) -> Result<&IntentPort, IntentGraphError> {
        let node = self
            .nodes
            .get(&leaf.node)
            .ok_or(IntentGraphError::UnknownNode(leaf.node))?;
        let port = node
            .ports
            .get(&leaf.port)
            .ok_or(IntentGraphError::UnknownPort {
                node: leaf.node,
                port: leaf.port,
            })?;
        if !port.writable.contains(&leaf.field) {
            return Err(IntentGraphError::UnknownWritableLeaf { leaf });
        }
        Ok(port)
    }

    /// Strict deterministic canonical graph JSON.
    ///
    /// # Errors
    ///
    /// Returns a structural, resource-limit, or serialization error.
    pub fn to_canonical_json(&self) -> Result<String, IntentGraphError> {
        self.validate()?;
        let mut wire = IntentGraphWire {
            version: INTENT_GRAPH_VERSION,
            graph: self.clone(),
            digest: ContentDigest::zero(),
        };
        wire.digest = graph_wire_digest(&wire);
        let json = serde_json::to_string(&wire)?;
        if json.len() > MAX_INTENT_GRAPH_JSON_BYTES {
            return Err(IntentGraphError::JsonResourceLimit {
                limit: MAX_INTENT_GRAPH_JSON_BYTES,
            });
        }
        Ok(json)
    }

    /// Imports strict canonical graph JSON and authenticates its digest.
    ///
    /// # Errors
    ///
    /// Returns an error for excessive, malformed, non-canonical, unsupported,
    /// digest-mismatched, or structurally invalid input.
    pub fn from_json(json: &str) -> Result<Self, IntentGraphError> {
        if json.len() > MAX_INTENT_GRAPH_JSON_BYTES {
            return Err(IntentGraphError::JsonResourceLimit {
                limit: MAX_INTENT_GRAPH_JSON_BYTES,
            });
        }
        let wire: IntentGraphWire = serde_json::from_str(json)?;
        if !matches!(
            wire.version,
            LEGACY_INTENT_GRAPH_VERSION | INTENT_GRAPH_VERSION
        ) {
            return Err(IntentGraphError::UnsupportedVersion {
                expected: INTENT_GRAPH_VERSION,
                actual: wire.version,
            });
        }
        let expected_digest = if wire.version == LEGACY_INTENT_GRAPH_VERSION {
            legacy_graph_wire_digest(&wire)
        } else {
            graph_wire_digest(&wire)
        };
        if wire.digest != expected_digest {
            return Err(IntentGraphError::DigestMismatch);
        }
        if serde_json::to_string(&wire)? != json {
            return Err(IntentGraphError::NonCanonicalJson);
        }
        wire.graph.validate()?;
        Ok(wire.graph)
    }
}

impl Default for IntentGraph {
    fn default() -> Self {
        Self::empty()
    }
}

#[derive(Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
struct IntentGraphWire {
    version: u32,
    graph: IntentGraph,
    digest: ContentDigest,
}

fn graph_wire_digest(wire: &IntentGraphWire) -> ContentDigest {
    digest_bytes(
        &serde_json::to_vec(&(wire.version, &wire.graph))
            .expect("graph wire payload is infallibly serializable"),
    )
}

fn legacy_graph_wire_digest(wire: &IntentGraphWire) -> ContentDigest {
    legacy_digest_bytes(
        &serde_json::to_vec(&(wire.version, &wire.graph))
            .expect("graph wire payload is infallibly serializable"),
    )
}

