#[allow(
    clippy::too_many_lines,
    reason = "draft completion atomically binds generated ports, identity flow, and instance leaves"
)]
pub(crate) fn finish_allocated_draft(
    allocated: AllocatedDraft,
    inputs: BTreeMap<crate::InputSlot, IntentPortRef>,
    instance: &mut IntentInstanceState,
) -> Result<IntentNode, IntentGraphError> {
    let identity_source = inputs
        .get(&crate::InputSlot::new(crate::InputRole::Identity, 0))
        .copied();
    let ports = allocated
        .ports
        .into_iter()
        .map(|(id, port)| {
            let flow = match &allocated.draft.kind {
                IntentNodeKind::Identity {
                    transition,
                    port_kind,
                } => {
                    let source = identity_source.ok_or(IntentGraphError::InputRoleNotAccepted {
                        node: allocated.id,
                        role: crate::InputRole::Identity,
                    })?;
                    if source.kind != *port_kind {
                        return Err(IntentGraphError::IdentityKindMismatch {
                            node: allocated.id,
                            expected: *port_kind,
                            actual: source.kind,
                        });
                    }
                    match transition {
                        crate::IdentityTransitionKind::Alias => {
                            IntentIdentityFlow::Aliased { source }
                        }
                        crate::IdentityTransitionKind::Continue => IntentIdentityFlow::Continued {
                            source,
                            generation: 0,
                        },
                        crate::IdentityTransitionKind::Retire => IntentIdentityFlow::Retired {
                            source,
                            generation: 0,
                        },
                    }
                }
                _ => match port.spec.alias_input.and_then(|slot| inputs.get(&slot)) {
                    Some(source) => IntentIdentityFlow::Aliased { source: *source },
                    None => port
                        .reservation
                        .map_or(IntentIdentityFlow::OwnedLogical, |reservation| {
                            IntentIdentityFlow::Created { reservation }
                        }),
                },
            };
            let writable = if matches!(flow, IntentIdentityFlow::Aliased { .. }) {
                Vec::new()
            } else {
                port.spec.writable.to_vec()
            };
            Ok((
                id,
                IntentPort {
                    id,
                    selector: port.spec.selector,
                    kind: port.spec.kind,
                    flow,
                    writable,
                },
            ))
        })
        .collect::<Result<BTreeMap<_, _>, IntentGraphError>>()?;

    for (selector, values) in &allocated.draft.initial_instance {
        let port = ports
            .values()
            .find(|port| port.selector == *selector)
            .ok_or(IntentGraphError::UnknownPortSelector {
                node: allocated.id,
                selector: *selector,
            })?;
        for (field, value) in values {
            if !port.writable.contains(field) || !literal_matches_leaf(value, *field) {
                return Err(IntentGraphError::UnknownWritableLeaf {
                    leaf: LeafRef {
                        node: allocated.id,
                        port: port.id,
                        field: *field,
                    },
                });
            }
            instance.values.insert(
                LeafRef {
                    node: allocated.id,
                    port: port.id,
                    field: *field,
                },
                value.clone(),
            );
        }
    }

    Ok(IntentNode {
        id: allocated.id,
        symbol: allocated.draft.symbol,
        kind: allocated.draft.kind,
        bootstrap_origin: None,
        suppressed: allocated.draft.suppressed,
        inputs,
        fields: allocated.draft.fields,
        operation_outputs: allocated.draft.operation_outputs,
        ports,
        reservations: allocated.reservations,
        child_order: allocated.child_order,
        children: allocated.children,
    })
}

pub(crate) fn assign_identity_generations(graph: &mut IntentGraph) -> Result<(), IntentGraphError> {
    validate_generation_references(graph)?;
    let schedule = graph.canonical_schedule()?;
    let mut generation = BTreeMap::<PortId, u64>::new();
    let mut token = BTreeMap::<PortId, PortId>::new();
    let mut current = BTreeMap::<PortId, u64>::new();
    for node_id in schedule {
        let port_ids = graph
            .nodes
            .get(&node_id)
            .ok_or(IntentGraphError::UnknownNode(node_id))?
            .ports
            .keys()
            .copied()
            .collect::<Vec<_>>();
        for port_id in port_ids {
            let flow = graph
                .nodes
                .get(&node_id)
                .and_then(|node| node.ports.get(&port_id))
                .ok_or(IntentGraphError::UnknownPort {
                    node: node_id,
                    port: port_id,
                })?
                .flow;
            match flow {
                IntentIdentityFlow::OwnedLogical | IntentIdentityFlow::Created { .. } => {
                    token.insert(port_id, port_id);
                    generation.insert(port_id, 0);
                    current.insert(port_id, 0);
                }
                IntentIdentityFlow::Aliased { source } => {
                    let root = referenced_value(&token, source.port, source)?;
                    let source_generation = referenced_value(&generation, source.port, source)?;
                    let current_generation = referenced_value(&current, root, source)?;
                    if current_generation != source_generation {
                        return Err(IntentGraphError::IdentityFork { port: source });
                    }
                    token.insert(port_id, root);
                    generation.insert(port_id, source_generation);
                }
                IntentIdentityFlow::Continued { source, .. }
                | IntentIdentityFlow::Retired { source, .. } => {
                    let root = referenced_value(&token, source.port, source)?;
                    let source_generation = referenced_value(&generation, source.port, source)?;
                    let expected = referenced_value(&current, root, source)?;
                    if source_generation != expected {
                        return Err(IntentGraphError::IdentityFork { port: source });
                    }
                    let next = expected
                        .checked_add(1)
                        .ok_or(IntentGraphError::IdExhausted("identity generation"))?;
                    token.insert(port_id, root);
                    generation.insert(port_id, next);
                    current.insert(root, next);
                    let port = graph
                        .nodes
                        .get_mut(&node_id)
                        .ok_or(IntentGraphError::UnknownNode(node_id))?
                        .ports
                        .get_mut(&port_id)
                        .ok_or(IntentGraphError::UnknownPort {
                            node: node_id,
                            port: port_id,
                        })?;
                    port.flow = match flow {
                        IntentIdentityFlow::Continued { source, .. } => {
                            IntentIdentityFlow::Continued {
                                source,
                                generation: next,
                            }
                        }
                        IntentIdentityFlow::Retired { source, .. } => IntentIdentityFlow::Retired {
                            source,
                            generation: next,
                        },
                        _ => unreachable!(),
                    };
                }
            }
        }
    }
    Ok(())
}

fn referenced_value<T: Copy>(
    values: &BTreeMap<PortId, T>,
    port: PortId,
    source: crate::IntentPortRef,
) -> Result<T, IntentGraphError> {
    values
        .get(&port)
        .copied()
        .ok_or(IntentGraphError::UnknownPort {
            node: source.node,
            port: source.port,
        })
}

fn validate_generation_references(graph: &IntentGraph) -> Result<(), IntentGraphError> {
    for (node_id, node) in &graph.nodes {
        for source in node.inputs.values() {
            validate_generation_reference(graph, *node_id, *source)?;
        }
        for port in node.ports.values() {
            match port.flow {
                IntentIdentityFlow::Aliased { source }
                | IntentIdentityFlow::Continued { source, .. }
                | IntentIdentityFlow::Retired { source, .. } => {
                    validate_generation_reference(graph, *node_id, source)?;
                }
                IntentIdentityFlow::OwnedLogical | IntentIdentityFlow::Created { .. } => {}
            }
        }
    }
    Ok(())
}

fn validate_generation_reference(
    graph: &IntentGraph,
    node: NodeId,
    source: crate::IntentPortRef,
) -> Result<(), IntentGraphError> {
    let owner = graph
        .nodes
        .get(&source.node)
        .ok_or(IntentGraphError::UnknownNode(source.node))?;
    let referenced = owner
        .ports
        .get(&source.port)
        .ok_or(IntentGraphError::UnknownPort {
            node: source.node,
            port: source.port,
        })?;
    if referenced.kind != source.kind {
        return Err(IntentGraphError::InputKindMismatch {
            node,
            expected: referenced.kind,
            actual: source.kind,
        });
    }
    Ok(())
}

#[allow(
    clippy::single_match_else,
    clippy::too_many_lines,
    reason = "one closed audit keeps generated ports, aliases, reservations, and the identity-node exception aligned"
)]
fn validate_schema_ports(node: &IntentNode) -> Result<(), IntentGraphError> {
    let dynamic_children = u16::try_from(node.children.len())
        .map_err(|_| IntentGraphError::InvalidPortSchema { node: node.id })?;
    let mut specs = node_port_specs(
        &node.kind,
        &node.fields,
        dynamic_children,
        &node.operation_outputs,
    );
    for (ordinal, child) in node.child_order.iter().enumerate() {
        let ordinal = u16::try_from(ordinal)
            .map_err(|_| IntentGraphError::InvalidPortSchema { node: node.id })?;
        let value = &node.children[child];
        specs.extend(child_port_specs(
            &node.kind,
            value.schema,
            ordinal,
            dynamic_children,
            &node.fields,
        ));
    }
    if specs.len() != node.ports.len() {
        return Err(IntentGraphError::InvalidPortSchema { node: node.id });
    }

    let mut used_reservations = BTreeSet::new();
    for spec in specs {
        let port = node
            .ports
            .values()
            .find(|port| port.selector == spec.selector)
            .ok_or(IntentGraphError::InvalidPortSchema { node: node.id })?;
        if port.kind != spec.kind {
            return Err(IntentGraphError::InvalidPortSchema { node: node.id });
        }
        match &node.kind {
            IntentNodeKind::Identity {
                transition,
                port_kind,
            } => {
                let source = node
                    .inputs
                    .get(&crate::InputSlot::new(crate::InputRole::Identity, 0))
                    .copied()
                    .ok_or(IntentGraphError::InvalidPortSchema { node: node.id })?;
                if *port_kind != port.kind
                    || !matches!(
                        (transition, port.flow),
                        (
                            crate::IdentityTransitionKind::Alias,
                            IntentIdentityFlow::Aliased { source: actual }
                        ) if actual == source
                    ) && !matches!(
                        (transition, port.flow),
                        (
                            crate::IdentityTransitionKind::Continue,
                            IntentIdentityFlow::Continued { source: actual, .. }
                        ) if actual == source
                    ) && !matches!(
                        (transition, port.flow),
                        (
                            crate::IdentityTransitionKind::Retire,
                            IntentIdentityFlow::Retired { source: actual, .. }
                        ) if actual == source
                    )
                    || !port.writable.is_empty()
                {
                    return Err(IntentGraphError::InvalidPortSchema { node: node.id });
                }
            }
            _ => {
                let alias_source = spec.alias_input.and_then(|slot| node.inputs.get(&slot));
                if let Some(source) = alias_source {
                    if port.flow != (IntentIdentityFlow::Aliased { source: *source })
                        || !port.writable.is_empty()
                    {
                        return Err(IntentGraphError::InvalidPortSchema { node: node.id });
                    }
                } else if let Some(native) = spec.native {
                    let IntentIdentityFlow::Created { reservation } = port.flow else {
                        return Err(IntentGraphError::InvalidPortSchema { node: node.id });
                    };
                    if node.reservations.get(&reservation).map(|value| value.kind) != Some(native) {
                        return Err(IntentGraphError::ReservationKindMismatch {
                            node: node.id,
                            port: port.id,
                        });
                    }
                    used_reservations.insert(reservation);
                    if port.writable != spec.writable {
                        return Err(IntentGraphError::InvalidPortSchema { node: node.id });
                    }
                } else if port.flow != IntentIdentityFlow::OwnedLogical
                    || port.writable != spec.writable
                {
                    return Err(IntentGraphError::InvalidPortSchema { node: node.id });
                }
            }
        }
    }
    if let Some(reservation) = node
        .reservations
        .keys()
        .find(|reservation| !used_reservations.contains(reservation))
    {
        return Err(IntentGraphError::UnusedReservation {
            node: node.id,
            reservation: *reservation,
        });
    }
    Ok(())
}

fn validate_port_reference(
    node: NodeId,
    source: IntentPortRef,
    ports: &BTreeMap<PortId, (NodeId, &IntentPort)>,
) -> Result<(), IntentGraphError> {
    let Some((owner, port)) = ports.get(&source.port) else {
        return Err(IntentGraphError::UnknownPort {
            node: source.node,
            port: source.port,
        });
    };
    if *owner != source.node {
        return Err(IntentGraphError::UnknownPort {
            node: source.node,
            port: source.port,
        });
    }
    if port.kind != source.kind {
        return Err(IntentGraphError::InputKindMismatch {
            node,
            expected: port.kind,
            actual: source.kind,
        });
    }
    Ok(())
}

fn canonical_schedule(
    nodes: &BTreeMap<NodeId, IntentNode>,
) -> Result<Vec<NodeId>, IntentGraphError> {
    let mut remaining = BTreeMap::<NodeId, usize>::new();
    let mut dependents = BTreeMap::<NodeId, BTreeSet<NodeId>>::new();
    for (node_id, node) in nodes {
        let dependencies = node.dependencies();
        for dependency in &dependencies {
            if !nodes.contains_key(dependency) {
                return Err(IntentGraphError::UnknownNode(*dependency));
            }
            dependents.entry(*dependency).or_default().insert(*node_id);
        }
        remaining.insert(*node_id, dependencies.len());
    }
    let mut ready = remaining
        .iter()
        .filter_map(|(node, count)| (*count == 0).then_some(*node))
        .collect::<BTreeSet<_>>();
    let mut schedule = Vec::with_capacity(nodes.len());
    while let Some(node) = ready.pop_first() {
        schedule.push(node);
        if let Some(values) = dependents.get(&node) {
            for dependent in values {
                let count = remaining
                    .get_mut(dependent)
                    .expect("every dependent is retained");
                *count -= 1;
                if *count == 0 {
                    ready.insert(*dependent);
                }
            }
        }
    }
    if schedule.len() != nodes.len() {
        let node = remaining
            .into_iter()
            .find_map(|(node, count)| (count != 0).then_some(node))
            .expect("a dependency cycle contains a node");
        return Err(IntentGraphError::DependencyCycle { node });
    }
    Ok(schedule)
}

#[derive(Clone, Copy)]
struct PortToken {
    root: PortId,
    generation: u64,
}

#[derive(Clone, Copy)]
struct TokenState {
    generation: u64,
    retired: bool,
}

#[allow(
    clippy::too_many_lines,
    reason = "one ordered pass plus final audit makes identity consumption and retirement explicit"
)]
fn validate_identity_flow(
    schedule: &[NodeId],
    nodes: &BTreeMap<NodeId, IntentNode>,
) -> Result<(), IntentGraphError> {
    let mut ports = BTreeMap::<PortId, PortToken>::new();
    let mut tokens = BTreeMap::<PortId, TokenState>::new();
    for node_id in schedule {
        for source in nodes[node_id].inputs.values() {
            let state = ports[&source.port];
            let token = tokens[&state.root];
            if token.retired {
                return Err(IntentGraphError::RetiredReference {
                    node: *node_id,
                    port: *source,
                });
            }
            if token.generation != state.generation {
                return Err(IntentGraphError::ConsumedReference {
                    node: *node_id,
                    port: *source,
                });
            }
        }
        for port in nodes[node_id].ports.values() {
            match port.flow {
                IntentIdentityFlow::OwnedLogical | IntentIdentityFlow::Created { .. } => {
                    ports.insert(
                        port.id,
                        PortToken {
                            root: port.id,
                            generation: 0,
                        },
                    );
                    tokens.insert(
                        port.id,
                        TokenState {
                            generation: 0,
                            retired: false,
                        },
                    );
                }
                IntentIdentityFlow::Aliased { source } => {
                    let state = ports[&source.port];
                    let token = tokens[&state.root];
                    if token.retired {
                        return Err(IntentGraphError::RetiredReference {
                            node: *node_id,
                            port: source,
                        });
                    }
                    if token.generation != state.generation {
                        return Err(IntentGraphError::IdentityFork { port: source });
                    }
                    ports.insert(port.id, state);
                }
                IntentIdentityFlow::Continued { source, generation }
                | IntentIdentityFlow::Retired { source, generation } => {
                    let source_state = ports[&source.port];
                    let token = tokens.get_mut(&source_state.root).unwrap();
                    if token.retired || token.generation != source_state.generation {
                        return Err(IntentGraphError::IdentityFork { port: source });
                    }
                    let expected = token
                        .generation
                        .checked_add(1)
                        .ok_or(IntentGraphError::IdExhausted("identity generation"))?;
                    if generation != expected {
                        return Err(IntentGraphError::InvalidGeneration {
                            node: *node_id,
                            expected,
                            actual: generation,
                        });
                    }
                    token.generation = generation;
                    token.retired = matches!(port.flow, IntentIdentityFlow::Retired { .. });
                    ports.insert(
                        port.id,
                        PortToken {
                            root: source_state.root,
                            generation,
                        },
                    );
                }
            }
        }
    }
    for (node_id, node) in nodes {
        for (slot, source) in &node.inputs {
            if matches!(node.kind, IntentNodeKind::Identity { .. })
                && slot.role == crate::InputRole::Identity
            {
                continue;
            }
            let state = ports[&source.port];
            let token = tokens[&state.root];
            if token.retired {
                return Err(IntentGraphError::RetiredReference {
                    node: *node_id,
                    port: *source,
                });
            }
            if token.generation != state.generation {
                return Err(IntentGraphError::ConsumedReference {
                    node: *node_id,
                    port: *source,
                });
            }
        }
    }
    Ok(())
}
