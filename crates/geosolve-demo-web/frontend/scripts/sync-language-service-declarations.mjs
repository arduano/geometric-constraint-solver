import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const frontendDirectory = resolve(scriptDirectory, "..");
const repositoryRoot = resolve(frontendDirectory, "../../..");
const sdkRoot = resolve(repositoryRoot, "packages/geosolve-sketch-code");
const output = resolve(
  frontendDirectory,
  "src/language/generated/language-service-declarations.ts",
);
const check = process.argv.includes("--check");
const expectedVersion = "5.9.2";

if (ts.version !== expectedVersion) {
  throw new Error(
    `language-service declarations require TypeScript ${expectedVersion}, found ${ts.version}`,
  );
}

const emitted = new Map();
const program = ts.createProgram({
  rootNames: [resolve(sdkRoot, "src/index.ts")],
  options: {
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.NodeNext,
    moduleResolution: ts.ModuleResolutionKind.NodeNext,
    strict: true,
    noUncheckedIndexedAccess: true,
    exactOptionalPropertyTypes: true,
    declaration: true,
    emitDeclarationOnly: true,
    skipLibCheck: true,
  },
});
const result = program.emit(undefined, (path, contents) => {
  emitted.set(path.replaceAll("\\", "/"), contents);
});
const errors = ts.getPreEmitDiagnostics(program)
  .concat(result.diagnostics)
  .filter((diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error);
if (errors.length > 0) {
  throw new Error(ts.formatDiagnosticsWithColorAndContext(errors, {
    getCanonicalFileName: (path) => path,
    getCurrentDirectory: () => repositoryRoot,
    getNewLine: () => "\n",
  }));
}

const declaration = (name) => {
  const entry = [...emitted].find(([path]) => path.endsWith(`/${name}.d.ts`));
  if (!entry) throw new Error(`TypeScript did not emit ${name}.d.ts`);
  return entry[1];
};

const libraryRoot = dirname(ts.getDefaultLibFilePath({ target: ts.ScriptTarget.ES2022 }));
const pendingLibraries = ["es2022"];
const libraries = new Map();
while (pendingLibraries.length > 0) {
  const name = pendingLibraries.pop();
  if (!name || libraries.has(name)) continue;
  const path = resolve(libraryRoot, `lib.${name}.d.ts`);
  const contents = await readFile(path, "utf8");
  libraries.set(name, contents);
  for (const match of contents.matchAll(/<reference lib="([^"]+)"/gu)) {
    pendingLibraries.push(match[1]);
  }
}

const standardLibrary = [...libraries]
  .sort(([left], [right]) => left.localeCompare(right))
  .map(([, contents]) => contents.replace(/^\s*\/\/\/\s*<reference (?:no-default-lib|lib)=[^\n]+\n?/gmu, ""))
  .join("\n");
const sdkIndex = declaration("index");
const sdkAuthoring = declaration("authoring");
const digest = createHash("sha256")
  .update(expectedVersion)
  .update("\0")
  .update(standardLibrary)
  .update("\0")
  .update(sdkIndex)
  .update("\0")
  .update(sdkAuthoring)
  .digest("hex");

const generated = `// SPDX-License-Identifier: GPL-3.0-or-later
// @generated by scripts/sync-language-service-declarations.mjs. Do not edit.

export const LANGUAGE_SERVICE_TYPESCRIPT_VERSION = ${JSON.stringify(expectedVersion)};
export const LANGUAGE_SERVICE_DECLARATIONS_DIGEST = ${JSON.stringify(digest)};
export const TYPESCRIPT_STANDARD_LIBRARY = ${JSON.stringify(standardLibrary)};
export const GEOSOLVE_SKETCH_CODE_INDEX = ${JSON.stringify(sdkIndex)};
export const GEOSOLVE_SKETCH_CODE_AUTHORING = ${JSON.stringify(sdkAuthoring)};
`;

if (check) {
  const current = await readFile(output, "utf8").catch(() => null);
  if (current !== generated) {
    throw new Error(
      `${relative(repositoryRoot, output)} is stale; run npm run generate:language-sdk`,
    );
  }
  console.log(
    `validated TypeScript ${expectedVersion} language declarations (${digest})`,
  );
} else {
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, generated);
  console.log(
    `generated TypeScript ${expectedVersion} language declarations (${digest})`,
  );
}
